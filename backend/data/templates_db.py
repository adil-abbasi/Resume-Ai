def build_full_template_catalog() -> List[TemplateItem]:
    """
    Builds the complete universal template catalog containing 120+ distinct templates
    spanning 12 industry categories with meaningful structural, typographic and layout differences.
    """
    catalog: List[TemplateItem] = []

    for raw in RAW_TEMPLATES:
        catalog.append(TemplateItem(
            id=raw["id"],
            name=raw["name"],
            description=raw["description"],
            category=raw["category"],
            is_pro=raw.get("is_pro", False),
            thumbnail_color=raw.get("thumbnail_color", "#2563EB"),
            secondary_color=raw.get("secondary_color", "#1E293B"),
            font_family=raw.get("font_family", "Inter"),
            layout_type=raw.get("layout_type", "single_column"),
            spacing=raw.get("spacing", "normal"),
            tags=raw.get("tags", []),
            rating=raw.get("rating", 4.9),
            downloads_count=raw.get("downloads_count", 1500),
            recommended_for=raw.get("recommended_for", []),
            industry=raw.get("industry", "General"),
            career_level=raw.get("career_level", "All Levels"),
            columns=raw.get("columns", 1),
            header_style=raw.get("header_style", "standard"),
            sidebar_position=raw.get("sidebar_position", "none"),
            ats_compatibility=raw.get("ats_compatibility", "High"),
            default_section_titles=raw.get("default_section_titles", {}),
            is_custom=False
        ))

    return catalog


ALL_TEMPLATES: List[TemplateItem] = build_full_template_catalog()
TEMPLATES_BY_ID: Dict[str, TemplateItem] = {t.id: t for t in ALL_TEMPLATES}


def get_templates(
    category: Optional[str] = None,
    search: Optional[str] = None,
    only_pro: Optional[bool] = None,
    industry: Optional[str] = None,
    ats_only: Optional[bool] = None
) -> List[TemplateItem]:
    """Filters template database by category, keyword search, pro tier, industry, or ATS compatibility."""
    results = ALL_TEMPLATES

    if category and category.lower() != "all":
        results = [t for t in results if t.category.lower() == category.lower()]

    if industry and industry.lower() != "all":
        results = [t for t in results if t.industry.lower() == industry.lower()]

    if only_pro is not None:
        results = [t for t in results if t.is_pro == only_pro]

    if ats_only:
        results = [t for t in results if t.ats_compatibility == "High"]

    if search:
        q = search.strip().lower()
        results = [
            t for t in results
            if q in t.name.lower()
            or q in t.description.lower()
            or any(q in tag for tag in t.tags)
            or q in t.category.lower()
            or q in t.industry.lower()
            or q in t.career_level.lower()
        ]

    return results
